// 永續祝福「逐格」像素臉的畫格資料（Figma 2065:131760，17 格）。
//
// 純資料模組（無 Vue runtime），Nuxt auto-import。座標單位＝ 16×16 網格的 1 格，
// 對應設計稿 288px ÷ 16 = 18px。17 格全部落在此網格上、零誤差（已驗算）。
// 多數方塊是 2×2 單位（＝稿上 36px），眼／嘴的中間態有 2×1 半格，最寬的嘴是 6×2。
//
// 序列：01–10 輪廓由頂端中央往外、往下長 → 11 輪廓完成（雙眼＋一點嘴）
//      → 12–13 嘴下移 → 14–15 嘴變寬 → 16–17 嘴角上揚成微笑。
//
// ── 兩種顏色 ──────────────────────────────────────────────────────
// 每個 rect 的第 5 個元素是「淺藍」旗標（accent）：1 = 淺藍（--color-blue #9fd6ff），
// 省略 = 白。淺藍出現在 02–10 格，標的是「該格新增的那幾塊」—— 新方塊先以淺藍冒出來、
// 下一格再轉白，逐格長輪廓時會有一圈淺藍的生長邊緣。11–17 格全白。
//
// ⚠️ 陣列順序＝ SVG 繪製順序，後面的蓋前面的，**不要排序**。
//    藍白方塊之間是半格（1 單位）錯位、會互相重疊，例如第 02 格的白色 [7,0] 疊在
//    藍色 [6,0] / [8,0] 之上；排序過就會變成藍色蓋住白色，圖形就錯了。
//
// ── 重新萃取的步驟（設計稿改版時照做）────────────────────────────────
//   1. Figma MCP：download_assets(fileKey, nodeId: '2065:131760', defaultFormat: 'svg')
//   2. 匯出的 SVG 只含「可見」圖層（Figma 會略過隱藏層），且整張被等比縮到 4096 寬；
//      先除以 4096/5536 還原成稿上 px，再減去該格的原點（第 n 格 x 偏移 = (n-1) × 328）。
//   3. 除以 18 得到本檔的網格單位。
//   4. fill 非 white（設計稿是 #9FD6FF）者標上 accent = 1。
//   5. **保留文件順序**，不要為了好讀而排序（理由見上）。
